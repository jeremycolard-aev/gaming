const makeEnemy = (x: number, y: number, range: number, speed = 1.2): Enemy => ({
  x, y, w: 28, h: 32,
  vx: speed,
  startX: x,
  patrolRange: range,
  waveTimer: Math.random() * 60,
  waveInterval: 90 + Math.random() * 40,
  alive: true,
})

const makeCoin = (x: number, y: number): Coin => ({
  x, y, r: 10,
  collected: false,
  waveTimer: Math.random() * 80,
})

